using BenchmarkDotNet.Attributes;

namespace Lotta.Benchmarks;

/// <summary>
/// Shared base for LottaDB throughput benchmarks.
/// Subclasses supply a provider-specific <see cref="Configure"/> action so the same
/// benchmark logic runs against every storage back-end.
/// </summary>
public abstract class LottaDBBenchmarkBase
{
    protected const int DocumentCount = 10_000;

    private static readonly string[] _animals = ["cat", "dog", "fish", "bird", "hamster"];
    private static readonly string[] _adjectives = ["quick", "lazy", "sleepy", "friendly", "grumpy"];

    private LottaCatalog _catalog = null!;
    private LottaDB _db = null!;

    /// <summary>Provider-specific catalog configuration (SQLite, Azure, …).</summary>
    protected abstract void Configure(LottaCatalog catalog);

    // ?? helpers ??????????????????????????????????????????????????????????????

    protected static string KeyFor(int i) => $"doc-{i:D6}";

    protected static BenchmarkDocument MakeDocument(int i)
    {
        var animal = _animals[i % _animals.Length];
        var adjective = _adjectives[i % _adjectives.Length];
        return new BenchmarkDocument
        {
            Id = KeyFor(i),
            Title = $"Document {i}",
            Content = $"The {adjective} {animal} jumps over the lazy fence. Index={i}.",
            Counter = i,
        };
    }

    // ?? lifecycle ?????????????????????????????????????????????????????????????

    [GlobalSetup]
    public async Task GlobalSetupAsync()
    {
        _catalog = new LottaCatalog(this.GetType().Name, Configure);
        _db = await _catalog.GetDatabaseAsync(_catalog.GetTableServiceClient().GetType().Name, config =>
        {
            config.Store<BenchmarkDocument>();
        });
        await _db.ResetDatabaseAsync();
    }

    [GlobalCleanup]
    public async Task GlobalCleanupAsync()
    {
        await _db.DeleteDatabaseAsync();
        _catalog.Dispose();
    }

    // ?? Benchmark 1: individual operations ????????????????????????????????????

    /// <summary>
    /// Saves 10 000 documents one at a time with <c>SaveAsync</c>, then:
    /// <list type="bullet">
    ///   <item><c>ChangeAsync</c> on every odd-id document</item>
    ///   <item><c>DeleteAsync</c> on every even-id document</item>
    ///   <item><c>GetAsync</c>   on every odd-id document</item>
    ///   <item><c>SearchAsync</c> for all documents that contain "dog"</item>
    /// </list>
    /// </summary>
    [Benchmark]
    public async Task Individual_Operations()
    {
        // ?? Save ?????????????????????????????????????????????????????????????
        for (int i = 0; i < DocumentCount; i++)
            await _db.SaveAsync(MakeDocument(i));

        // ?? Change odd-id documents ???????????????????????????????????????????
        for (int i = 1; i < DocumentCount; i += 2)
            await _db.ChangeAsync<BenchmarkDocument>(KeyFor(i), doc => { doc.Counter += 1; });

        // ?? Delete even-id documents ??????????????????????????????????????????
        for (int i = 0; i < DocumentCount; i += 2)
            await _db.DeleteAsync<BenchmarkDocument>(KeyFor(i));

        // ?? Get odd-id documents ??????????????????????????????????????????????
        for (int i = 1; i < DocumentCount; i += 2)
            _ = await _db.GetAsync<BenchmarkDocument>(KeyFor(i));

        // ?? Search for "dog" ??????????????????????????????????????????????????
        _ = _db.Search<BenchmarkDocument>("dog").ToList();

        // Reset for next iteration
        await _db.ResetDatabaseAsync();
    }

    // ?? Benchmark 2: bulk / batch operations ??????????????????????????????????

    /// <summary>
    /// Saves 10 000 documents in one <c>SaveManyAsync</c> call, then:
    /// <list type="bullet">
    ///   <item><c>ChangeAsync</c>      on every odd-id document</item>
    ///   <item><c>DeleteManyAsync</c>  on even-id documents</item>
    ///   <item><c>GetManyAsync</c>     on all remaining documents</item>
    ///   <item><c>SearchAsync</c>      for all documents that contain "dog"</item>
    /// </list>
    /// </summary>
    [Benchmark]
    public async Task Batch_Operations()
    {
        var docs = Enumerable.Range(0, DocumentCount).Select(i => MakeDocument(i)).ToList();

        // ?? SaveManyAsync ?????????????????????????????????????????????????????
        await _db.SaveManyAsync(docs);

        // ?? ChangeAsync odd-id documents ??????????????????????????????????????
        for (int i = 1; i < DocumentCount; i += 2)
            await _db.ChangeAsync<BenchmarkDocument>(KeyFor(i), doc => { doc.Counter += 1; });

        // ?? DeleteManyAsync even-id documents ?????????????????????????????????
        var evenKeys = Enumerable.Range(0, DocumentCount / 2).Select(n => KeyFor(n * 2)).ToList();
        await _db.DeleteManyAsync(evenKeys);

        // ?? GetManyAsync all remaining (odd) documents ????????????????????????
        _ = await _db.GetManyAsync<BenchmarkDocument>().ToListAsync();

        // ?? Search for "dog" ??????????????????????????????????????????????????
        _ = _db.Search<BenchmarkDocument>("dog").ToList();

        // Reset for next iteration
        await _db.ResetDatabaseAsync();
    }
}
